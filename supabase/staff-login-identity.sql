alter table public.staff_members
  alter column id set generated by default;

create or replace function public.reserve_staff_member_id()
returns bigint
language sql
security definer
set search_path = ''
as $reserve_staff_member_id$
  select pg_catalog.nextval(
    pg_catalog.pg_get_serial_sequence('public.staff_members', 'id')::regclass
  )::bigint;
$reserve_staff_member_id$;

revoke all on function public.reserve_staff_member_id() from public, anon, authenticated;
grant execute on function public.reserve_staff_member_id() to service_role;

update public.profiles as profile
set username = staff.employee_code
from public.staff_members as staff
where profile.id = staff.user_id
  and profile.username is distinct from staff.employee_code
  and not exists (
    select 1
    from public.profiles as other_profile
    where other_profile.username = staff.employee_code
      and other_profile.id <> profile.id
  );
