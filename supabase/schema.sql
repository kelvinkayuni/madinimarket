create extension if not exists "pgcrypto";

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null,
  username text not null unique,
  phone text,
  avatar_url text,
  created_at timestamptz default now() not null
);

create table if not exists public.listings (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  mineral_name text not null,
  weight numeric not null,
  unit text not null check (unit in ('carats', 'g', 'kg', 'tons')),
  price numeric not null,
  currency text not null check (currency in ('TZS', 'USD')),
  seller_name text not null,
  country text not null,
  region text not null,
  district text not null,
  street text not null,
  email text not null,
  phone text not null,
  image_url text,
  is_active boolean default true not null,
  created_at timestamptz default now() not null
);

create table if not exists public.buy_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  mineral_name text not null,
  weight text not null,
  unit text not null check (unit in ('carats', 'g', 'kg', 'tons')),
  color text not null,
  shape text not null check (shape in ('Cut', 'Uncut')),
  quality text not null,
  offer numeric not null,
  currency text not null check (currency in ('TZS', 'USD')),
  buyer_name text not null,
  location text not null,
  email text not null,
  phone text not null,
  is_active boolean default true not null,
  created_at timestamptz default now() not null
);

alter table public.profiles enable row level security;
alter table public.listings enable row level security;
alter table public.buy_requests enable row level security;

create policy "Users can view profiles" on public.profiles
  for select using (true);

create policy "Users can insert profile" on public.profiles
  for insert with check (auth.uid() = id);

create policy "Users can update profile" on public.profiles
  for update using (auth.uid() = id);

create policy "Users can manage their listings" on public.listings
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

create policy "Users can manage their buy requests" on public.buy_requests
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

create policy "Anyone can read active listings" on public.listings
  for select using (is_active = true);

create policy "Anyone can read active buy requests" on public.buy_requests
  for select using (is_active = true);

create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, display_name, username, phone)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'display_name', split_part(new.email, '@', 1)),
    coalesce(new.raw_user_meta_data ->> 'username', 'MM-' || lpad(floor(random() * 10000)::int::text, 4, '0')),
    new.raw_user_meta_data ->> 'phone'
  )
  on conflict (id) do nothing;
  return new;
end;
$$ language plpgsql security definer;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();
